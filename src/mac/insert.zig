//! Inserting text into the app in front: through the pasteboard and a
//! synthetic `⌘V`.
//!
//! The palette is a non-activating panel, so the app the user typed in stays
//! active the whole time; once the panel is ordered out, its window gets the
//! keyboard back and the posted `⌘V` lands at its insertion point.
//!
//! Posting key events to other apps needs the Accessibility permission.
//! While a password field holds secure event input, macOS drops synthetic
//! key events silently; callers check `secureInputActive` and only copy.
//!
//! The pasteboard is borrowed, not taken: `stage` remembers every item that
//! was there, marks the inserted text as transient so clipboard managers
//! skip it, and `Staged.restore` puts the old items back unless something
//! else wrote to the pasteboard in between. Main thread only.
const std = @import("std");
const nanoui = @import("nanoui");
const objc = nanoui.objc;
const launch = @import("launch.zig");

/// System Settings, Privacy & Security, Accessibility.
pub const accessibility_settings = "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility";

/// The nspasteboard.org types for content clipboard managers should not record.
const transient_types = [_][]const u8{ "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType" };

/// `kVK_ANSI_V`: the V key position, also on German layouts.
const key_v: u16 = 9;
const flag_command: u64 = 0x0010_0000;

extern "c" fn AXIsProcessTrusted() u8;
extern "c" fn AXIsProcessTrustedWithOptions(options: ?*anyopaque) u8;
extern "c" fn IsSecureEventInputEnabled() u8;
extern "c" fn CGEventSourceCreate(state: i32) ?*anyopaque;
extern "c" fn CGEventCreateKeyboardEvent(source: ?*anyopaque, key: u16, down: bool) ?*anyopaque;
extern "c" fn CGEventSetFlags(event: *anyopaque, flags: u64) void;
extern "c" fn CGEventPost(tap: u32, event: *anyopaque) void;
extern "c" fn CFRelease(object: *anyopaque) void;

/// Whether macOS lets Zugriff post key events to other apps.
pub fn isTrusted() bool {
    return AXIsProcessTrusted() != 0;
}

/// Asks `isTrusted` once on a helper thread. The first answer of a process
/// comes from the TCC daemon (about 11 ms on macOS 27.2), later ones from a
/// cache; started while AppKit sets up, the first show no longer waits for
/// it on the main thread. Without a thread the first show asks itself.
pub fn prefetchTrust() void {
    const t = std.Thread.spawn(.{}, struct {
        fn ask() void {
            _ = isTrusted();
        }
    }.ask, .{}) catch return;
    t.detach();
}

/// Whether some app holds secure event input (a focused password field).
pub fn secureInputActive() bool {
    return IsSecureEventInputEnabled() != 0;
}

/// Asks macOS for the Accessibility permission and opens its settings page.
/// The system prompt appears only the first time; it also adds Zugriff to
/// the list in System Settings, so the user only has to switch it on.
pub fn requestTrust() void {
    const pool = objc.Pool.push();
    defer pool.pop();
    const yes = objc.msg(objc.Object, objc.class("NSNumber"), "numberWithBool:", .{objc.YES});
    const options = objc.msg(
        objc.Object,
        objc.class("NSDictionary"),
        "dictionaryWithObject:forKey:",
        .{ yes, objc.nsString("AXTrustedCheckOptionPrompt") },
    );
    _ = AXIsProcessTrustedWithOptions(@ptrCast(options));
    launch.openAddress(accessibility_settings);
}

/// The pasteboard as it was before `stage` replaced it: every item's types
/// and data, retained until `restore` or `discard`.
pub const Staged = struct {
    items: ?objc.Object,
    change_count: objc.NSInteger,

    /// Puts the previous items back, unless something else wrote to the
    /// pasteboard since `stage`. Returns whether it restored them.
    pub fn restore(s: Staged) bool {
        defer s.discard();
        const pool = objc.Pool.push();
        defer pool.pop();
        const pb = pasteboard();
        if (objc.msg(objc.NSInteger, pb, "changeCount", .{}) != s.change_count) return false;
        _ = objc.msg(objc.NSInteger, pb, "clearContents", .{});
        const saved = s.items orelse return true;
        const n = objc.msg(objc.NSUInteger, saved, "count", .{});
        if (n == 0) return true;
        const out = objc.msg(objc.Object, objc.class("NSMutableArray"), "array", .{});
        for (0..n) |i| {
            const entries = objc.msg(objc.Object, saved, "objectAtIndex:", .{i});
            const item = objc.msg(objc.Object, objc.class("NSPasteboardItem"), "new", .{});
            objc.autorelease(item);
            const keys = objc.msg(objc.Object, entries, "allKeys", .{});
            for (0..objc.msg(objc.NSUInteger, keys, "count", .{})) |k| {
                const kind = objc.msg(objc.Object, keys, "objectAtIndex:", .{k});
                const data = objc.msg(objc.Object, entries, "objectForKey:", .{kind});
                _ = objc.msg(objc.BOOL, item, "setData:forType:", .{ data, kind });
            }
            objc.msg(void, out, "addObject:", .{item});
        }
        if (!objc.msg(objc.BOOL, pb, "writeObjects:", .{out})) std.log.warn(
            "Zwischenablage hat die Einträge nicht übernommen",
            .{},
        );
        return true;
    }

    pub fn discard(s: Staged) void {
        if (s.items) |i| objc.release(i);
    }
};

fn pasteboard() objc.Object {
    return objc.msg(objc.Object, objc.class("NSPasteboard"), "generalPasteboard", .{});
}

/// Puts `text` on the general pasteboard for one paste and remembers what
/// was there.
pub fn stage(text: []const u8) Staged {
    const pool = objc.Pool.push();
    defer pool.pop();
    const pb = pasteboard();
    const saved = snapshot(pb);
    _ = objc.msg(objc.NSInteger, pb, "clearContents", .{});
    const item = objc.msg(objc.Object, objc.class("NSPasteboardItem"), "new", .{});
    objc.autorelease(item);
    _ = objc.msg(
        objc.BOOL,
        item,
        "setString:forType:",
        .{ objc.nsString(text), objc.nsString("public.utf8-plain-text") },
    );
    const marker = objc.msg(objc.Object, objc.class("NSData"), "data", .{});
    for (transient_types) |t| _ = objc.msg(objc.BOOL, item, "setData:forType:", .{ marker, objc.nsString(t) });
    const items = objc.msg(objc.Object, objc.class("NSArray"), "arrayWithObject:", .{item});
    if (!objc.msg(objc.BOOL, pb, "writeObjects:", .{items})) std.log.warn(
        "Zwischenablage hat das Emoji nicht übernommen",
        .{},
    );
    return .{ .items = saved, .change_count = objc.msg(objc.NSInteger, pb, "changeCount", .{}) };
}

/// Every item as a dictionary from type to data, retained.
fn snapshot(pb: objc.Object) ?objc.Object {
    const items = objc.msg(?objc.Object, pb, "pasteboardItems", .{}) orelse return null;
    const out = objc.msg(objc.Object, objc.alloc("NSMutableArray"), "init", .{});
    for (0..objc.msg(objc.NSUInteger, items, "count", .{})) |i| {
        const item = objc.msg(objc.Object, items, "objectAtIndex:", .{i});
        const entries = objc.msg(objc.Object, objc.class("NSMutableDictionary"), "dictionary", .{});
        const types = objc.msg(objc.Object, item, "types", .{});
        for (0..objc.msg(objc.NSUInteger, types, "count", .{})) |t| {
            const kind = objc.msg(objc.Object, types, "objectAtIndex:", .{t});
            const data = objc.msg(?objc.Object, item, "dataForType:", .{kind}) orelse continue;
            objc.msg(void, entries, "setObject:forKey:", .{ data, kind });
        }
        objc.msg(void, out, "addObject:", .{entries});
    }
    return out;
}

pub const PasteError = error{ NotTrusted, SecureInput, Event };

/// Posts `⌘V` to the window that has the keyboard.
pub fn postPaste() PasteError!void {
    if (!isTrusted()) return error.NotTrusted;
    if (secureInputActive()) return error.SecureInput;
    const source = CGEventSourceCreate(1) orelse return error.Event; // HID system state
    defer CFRelease(source);
    for ([_]bool{ true, false }) |down| {
        const event = CGEventCreateKeyboardEvent(source, key_v, down) orelse return error.Event;
        defer CFRelease(event);
        CGEventSetFlags(event, flag_command);
        CGEventPost(0, event); // kCGHIDEventTap
    }
}
